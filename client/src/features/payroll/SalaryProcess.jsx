/* Factor HR's SALARY PROCESS, photographed 29 August 2026 on MAR 2026, drawn
   control for control: three lists, the strip of twelve month chips with a "+"
   on the end, the summary line, the six tiles, Generated By / On with Payslip
   Remarks, and then Start Salary Process, Finalize Process and the gear.

   The screen splits cleanly in two, and the split is the honest part of it:

   **Above the summary line it is date arithmetic**, and all of it is live here.
   Which payroll year, which month, what the payroll period is and how many
   calendar days it holds are answerable without reading a single payroll row —
   they are the same twelve months the Payslip screen already walks, off the
   same fyMonths().

   **Below it, it is payroll state**, read off the site since 29 Sep 2026: the
   month's Payroll Entry, its Salary Slips and who has a salary structure —
   api/payroll.js, and lib/payroll.js for what they mean. Stop Salary, Stop
   Payment and Arrears are still dashes: nothing on the site means what those
   tiles mean. See SP_TILES.

   **Two steps of the run are here and the third is not.** Start Salary Process
   makes the draft Payroll Entry and picks the people; Create Salary Slips
   submits it and hrms makes a draft slip each. Neither pays anybody. Finalize
   submits the slips, which books the pay, and it opens the entry on the desk —
   see apiSubmitDraft in api/client.js. The gear goes to Payroll Settings, where
   **Consider Unmarked Attendance As** decides whether a day the shift job has
   not processed yet is a day's pay gone. CLAUDE.md §5 arriving from the
   payroll side. */

/** Their date format on the summary line — "01 Mar - 31 Mar 2026". Not `dmy`,
    which writes 01-Mar-2026: this is one line of their screen and it is written
    the way that line writes it, so the two can be read side by side. */
const spanSaid = (a, b) =>
	`${a.getDate().toString().padStart(2, "0")} ${MON[a.getMonth()]} - `
	+ `${b.getDate().toString().padStart(2, "0")} ${MON[b.getMonth()]} ${b.getFullYear()}`;

/* One extra read, made the first time somebody opens this screen — not part of
   the load every page pays for.

   `relieving_date` is asked for on its own because their −13 tile is precisely
   the question of whether this site carries it, and a field the site does not
   have would fail the read that draws the whole dashboard if it were added to
   EMP_FIELDS. A refusal is an answer, and it is a different answer from nobody
   having left in the month: the page says which it got. */
async function spProbe() {
	if (getState().spLeftState) return;
	set({ spLeftState: "loading" });

	const rows = await listAll("Employee", ["name", "relieving_date"]).catch(() => null);

	set(rows
		? { spLeft: Object.fromEntries(rows.map((r) => [r.name, r.relieving_date || ""])), spLeftState: "ok" }
		: { spLeft: null, spLeftState: "absent" });
}

/** Who the run would produce a slip for, in the chosen month.

    Employment overlapping the month, not "Active today" — somebody who left on
    the 14th is still owed fourteen days, which is what their tile's "incl. left"
    is about. When `relieving_date` could not be read the rule falls back to
    status and the page says so rather than quietly counting a different
    population: refusing somebody who did work is the expensive mistake, so the
    fallback keeps everybody Active and loses only the part-month leavers. */
function runFor(s, iso) {
	const [start, end] = iso;
	const left = s.spLeft;

	return scoped(s).filter((e) => {
		if (e.date_of_joining && e.date_of_joining > end) return false;
		if (left) {
			const rel = left[e.name];
			return rel ? rel >= start : e.status !== "Left";
		}
		return e.status === "Active";
	});
}

/** One tile. `n` is the figure, `s` the small print under the label, and a null
    `n` is drawn as a dash with the reason on it — the two tiles nothing here
    can mean are the point of the strip, not a gap in it. */
function SpTile({ label, sub, n, why, warn }) {
	return (
		<div className={"sptile" + (n == null ? " dead" : "") + (warn ? " warn" : "")} title={why}>
			<span className="k">
				{label}
				{sub ? <small> {sub}</small> : null}
			</span>
			<b className="n">{n == null ? "—" : n}</b>
		</div>
	);
}

/** What this screen can honestly put in a file: who the chosen month's run
    would cover, and whether each of them has the two things that decide their
    payment days. Not a payroll file — there is no amount on this side to put
    in one, and the heading row says so. */
function spCsv(rows, ym, s) {
	const cols = ["Employee code", "Name", "Company", "Status", "Joined", "Relieved",
		"Holiday list", "Month"];
	download(
		"salary-process-" + ym + ".csv",
		toCsv(cols, rows.map((e) => [
			e.employee_number || e.name,
			e.employee_name || "",
			e.company || "",
			e.status || "",
			e.date_of_joining || "",
			(s.spLeft && s.spLeft[e.name]) || "",
			e.holiday_list || "",
			ym,
		])),
	);
}

export default function SalaryProcess() {
	const s = useApp();
	const f = s.sp;

	/* Read once, on arrival. Every other screen pays nothing for it. */
	useEffect(() => { void spProbe(); }, []);

	/* Both resolved at render rather than seeded in the store: this is the one
	   screen where the month decides what everybody is paid, and a default fixed
	   at module load is a default that is wrong for anybody who left the tab open
	   over a month end. */
	const year = f.year || fyOf(todayIso());
	const months = fyMonths(year);
	const now = todayIso().slice(0, 7);
	/* Their capture had the last month of the chosen year selected while the
	   clock was well past it, which is what a year you are no longer in looks
	   like. Same rule here: this month if it is in this year, otherwise the last
	   one that is. */
	const month = f.month && months.some(([ym]) => ym === f.month)
		? f.month
		: (months.some(([ym]) => ym === now) ? now : months[months.length - 1][0]);

	const per = periodOf(month);
	const [start, end] = per.iso;
	const label = (MON[Number(month.slice(5, 7)) - 1] + " " + month.slice(0, 4)).toUpperCase();

	/* The month on the site. Read again when the month or the company changes;
	   one company's month is one Payroll Entry, so "All companies" reads the
	   group's slips and can start nothing. */
	const company = s.company;
	useEffect(() => { void loadPayroll(company, start, end); }, [company, start, end]);
	const pay = s.pay[payKey(company, start, end)] || { state: "" };
	const ok = pay.state === "ok";
	const entry = ok ? entryFor(pay.entries) : null;
	const slips = ok ? pay.slips : [];
	const state = ok ? runState(entry, slips) : "";
	const tot = slipTotals(slips);

	const run = runFor(s, per.iso);
	const bare = ok ? withoutStructure(run, pay.assignments, end) : [];
	const joined = run.filter((e) => e.date_of_joining >= start && e.date_of_joining <= end);
	const leftIn = s.spLeft
		? run.filter((e) => {
			const rel = s.spLeft[e.name];
			return rel && rel >= start && rel <= end;
		})
		: null;

	/* The two things that decide payment days, and both are the blocker rather
	   than a detail of it: without a holiday list a week-off is a working day
	   that nobody worked, and without Attendance there is nothing to divide the
	   month by at all. */
	/* "Could not be read" and "still reading" are different answers, and the
	   tile is the one place somebody looks for the second one. */
	const leftWhy = leftIn
		? `${leftIn.length} left in ${label}, off relieving_date`
		: s.spLeftState === "loading"
			? "Reading relieving_date…"
			: "relieving_date could not be read on this site, so leavers in the month cannot be counted"
				+ " — see the note under the screen.";

	const noList = run.filter((e) => !e.holiday_list);
	const att = s.counts.attendance || 0;
	const lists = s.counts.holiday || 0;

	const value = {
		total: fmt(run.length),
		pending: ok ? fmt(Math.max(0, run.length - tot.count)) : "…",
		process: ok ? fmt(tot.count) + " / " + fmt(run.length) : "…",
		stopsal: null,
		stoppay: null,
		arrears: null,
	};

	/* Why Start is refused, in the order somebody would fix them. */
	const startWhy = !company ? "Pick a company in the top bar — a salary run is one company's month."
		: month > now ? `${label} has not happened yet.`
			: !ok ? "Reading this month's payroll…"
				: entry ? `${entry.name} is already this month's run.`
					: f.busy ? "Busy…" : "";

	async function onStart() {
		patch("sp", { busy: "start", msg: "", err: "", confirm: "" });
		try {
			const name = await startSalaryProcess(company, start, end, end);
			patch("sp", { busy: "", msg: `${name} made, and hrms has picked who is on it. Check the list on the site if you want to, then Create Salary Slips.` });
		} catch (e) {
			patch("sp", { busy: "", err: e.message || String(e) });
		}
		await loadPayroll(company, start, end, { fresh: true });
	}

	async function onSlips() {
		patch("sp", { busy: "slips", msg: "", err: "" });
		try {
			await createSalarySlips(entry.name);
			patch("sp", { busy: "", confirm: "", msg: `${entry.name} submitted — hrms is making the draft slips. Nothing is paid until Finalize.` });
		} catch (e) {
			patch("sp", { busy: "", confirm: "", err: e.message || String(e) });
		}
		await loadPayroll(company, start, end, { fresh: true });
	}

	return (
		<>
			<div className="fhscreen">
				<div className="spbar">
					<span className="adf">
						<label htmlFor="sp-year">Year</label>
						{/* Live. A payroll year is April to March and the label is theirs. */}
						<select id="sp-year" value={year}
							title="April to March, written the way their box writes it. Live — it is arithmetic on the clock, not a payroll read."
							onChange={(e) => patch("sp", { year: e.target.value, month: "" })}>
							{fyList(todayIso()).map((y) => <option key={y}>{y}</option>)}
						</select>
					</span>
					<span className="adf">
						<label htmlFor="sp-type">Payroll Type</label>
						{/* The same control their Payslip screen carries, and the same single
						    value — so it reuses that list rather than declaring a second one
						    which could drift from it. */}
						<select id="sp-type" disabled value={f.ptype}
							title="Monthly was the value in the capture, on this screen and on their payslip form. Neither list has been opened, so one value is all this offers."
							onChange={() => {}}>
							{PSL_PAYROLL_TYPES.map((t) => <option key={t}>{t}</option>)}
						</select>
					</span>
					<span className="adf">
						<label htmlFor="sp-for">Process For</label>
						<select id="sp-for" disabled value={f.pfor}
							title="All Employees was the value in the capture and the list was never opened. On our side the same idea is the filters on a Payroll Entry — branch, department, designation — which choose who the run covers."
							onChange={() => {}}>
							{SP_PROCESS_FOR.map((t) => <option key={t}>{t}</option>)}
						</select>
					</span>
				</div>

				{/* Their month strip, April first — payroll order, not calendar order. */}
				<Scroll>
					<div className="spmonths" role="tablist" aria-label="Payroll month">
						{months.map(([ym, name]) => {
							const on = ym === month;
							/* A month that has not finished cannot be run, and their screen
							   makes no distinction — ours says it in a tooltip rather than by
							   refusing the click, because looking at next month is not the
							   mistake; paying it is. */
							const ahead = ym > now;
							return (
								<button key={ym} {...tabProps("spm-" + ym, "sp-panel", on)}
									className={"spm" + (on ? " on" : "") + (ahead ? " ahead" : "")}
									title={ahead ? name + " has not happened yet." : name}
									onClick={() => patch("sp", { month: ym })}>
									<b>{MON[Number(ym.slice(5, 7)) - 1].toUpperCase()}</b>
									<small>{ym.slice(0, 4)}</small>
								</button>
							);
						})}
						{/* Their "+". Never pressed, so what it adds is unknown — an extra
						    off-cycle period is the obvious reading and it is only a reading,
						    so nothing is invented behind it. */}
						<button className="spm add" disabled
							title="Their +, which has never been pressed. What it adds is unknown and nothing is invented in its place.">
							+
						</button>
					</div>
				</Scroll>

				<div className="sppanel" {...panelProps("sp-panel", "spm-" + month)}>
					<div className="spsum">
						<b>{label}</b>
						<span>
							<i>Payroll date:</i> {spanSaid(per.from, per.till)} | Calendar days {per.days}
						</span>
						{/* Two ranges on their line, and identical in the capture. They are
						    separate controls there, which is how a cut-off other than the
						    month end gets said — 26th to 25th, say. A Payroll Entry has one
						    period for both, so a cut-off would be a custom field and a change
						    to how attendance is counted, not a setting. */}
						<span title="Identical to the payroll date in their capture. Theirs are two separate ranges, which is how an attendance cut-off other than the month end would be said; a Payroll Entry has one period for both.">
							<i>Attendance date:</i> {spanSaid(per.from, per.till)} | Calendar days {per.days}
						</span>
						<span className="st" title={entry ? `${entry.name} on the site.` : "No Payroll Entry for this month on the site."}>
							<i>Status:</i> {ok ? RUN_STATES[state] : pay.state === "error" ? "COULD NOT BE READ" : "READING…"}
						</span>
					</div>

					<div className="sptiles">
						<SpTile label="Total employees" sub="(incl. left)" n={
							<>
								{value.total}
								<em className="up" title={`${joined.length} joined in ${label}, off date_of_joining`}>
									+{joined.length}
								</em>
								<em className="dn" title={leftWhy}>
									{leftIn ? "−" + leftIn.length : (s.spLeftState === "loading" ? "−…" : "−?")}
								</em>
							</>
						} why={SP_TILES[0].why} />
						{SP_TILES.slice(1).map((t) => (
							<SpTile key={t.k} label={t.label} sub={t.sub} n={value[t.k]} why={t.why}
								warn={!t.map} />
						))}
					</div>
					</div>

				<div className="spgen">
					<span><i>Generated By:</i> {entry?.owner || "—"}</span>
					<span><i>Generated On:</i> {entry?.creation ? dmyTime(entry.creation) : "—"}</span>
					<label htmlFor="sp-rem"><i>Payslip Remarks:</i></label>
					<input id="sp-rem" disabled value={f.remarks} onChange={() => {}}
						title="A note carried onto the run. Nothing here writes payroll, so there is nothing for it to be carried onto — it is written against the Payroll Entry, on the site." />
				</div>

				<div className="spacts">
					<b className="font-display">Salary Process</b>
					<button type="button" className="embtn pri" disabled={Boolean(startWhy)}
						title={startWhy || SP_ACTIONS[0][2]} onClick={() => void onStart()}>
						{f.busy === "start" ? "Starting…" : "Start Salary Process"}
					</button>
					{/* Their split caret, which has never been opened. */}
					<button className="embtn pri split" disabled aria-label="Start options"
						title="Their caret, never opened. What it offers is unknown and nothing is invented in its place.">
						▾
					</button>
					{state === "draft" ? (
						f.confirm === "slips" ? (
							<>
								<button type="button" className="embtn pri" disabled={Boolean(f.busy)}
									onClick={() => void onSlips()}>
									{f.busy === "slips" ? "Creating…" : `Yes, create ${fmt(entry.number_of_employees || run.length)} slips`}
								</button>
								<button type="button" className="embtn" disabled={Boolean(f.busy)}
									onClick={() => patch("sp", { confirm: "" })}>
									Cancel
								</button>
							</>
						) : (
							<button type="button" className="embtn pri"
								title="Submits the Payroll Entry, and hrms makes a draft salary slip for each person on it. Nothing is paid until Finalize."
								onClick={() => patch("sp", { confirm: "slips", msg: "", err: "" })}>
								Create Salary Slips
							</button>
						)
					) : null}
					<Desk className="embtn pri" href={s.site && (entry ? deskUrl(s.site, "Payroll Entry", entry.name) : deskUrl(s.site, "Payroll Entry"))}
						label="Finalize Process" title={SP_ACTIONS[1][2]}>
						Finalize Process
					</Desk>
					<Desk className="embtn gear" href={s.site && deskUrl(s.site, "Payroll Settings")}
						label="Payroll settings" title={SP_ACTIONS[2][2]}>
						⚙
					</Desk>
					<button type="button" className="embtn" disabled={pay.state === "loading"}
						title="Read this month's payroll off the site again — slips made in the background appear here once they exist."
						onClick={() => void loadPayroll(company, start, end, { fresh: true })}>
						Refresh
					</button>
					<button className="embtn spexp" onClick={() => spCsv(run, month, s)}
						title="Export who this month's run would cover, with the two fields that decide their payment days. Not a payroll file — there is no amount on this side to put in one.">
						Export the run
					</button>
				</div>
			</div>

			{f.msg ? <Gap>{f.msg}</Gap> : null}
			{f.err ? <Gap><b>Not done.</b> {f.err}</Gap> : null}

			<div className="mt-[1rem]">
				{pay.state === "error" ? <Gap><b>Payroll could not be read.</b> {pay.err}</Gap> : null}
				{ok && tot.count ? (
					<Gap>
						<b>{fmt(tot.count)} slip{tot.count === 1 ? "" : "s"}</b> for {label}
						{company ? <> at {company}</> : <> across the group</>}
						{" · "}{fmt(tot.submitted)} finalized, {fmt(tot.count - tot.submitted)} in draft
						{" · "}gross {fmt(Math.round(tot.gross))}, deductions {fmt(Math.round(tot.deduction))},
						net <b>{fmt(Math.round(tot.net))}</b>. Every figure is hrms&apos;s own, off the slips.
						{tot.count > tot.submitted ? <> A draft slip pays nobody — Finalize does.</> : null}
					</Gap>
				) : null}
				{state === "queued" ? (
					<Gap>
						<b>hrms is making the slips.</b> Past thirty people it does it in the background; press
						Refresh in a minute. If nothing appears, the entry on the site says why.
					</Gap>
				) : null}
				{ok && bare.length ? (
					<Gap>
						<b>{fmt(bare.length)} of {fmt(run.length)} people have no salary structure for {label}</b>
						{" "}— {bare.slice(0, 8).map((e) => e.employee_name || e.name).join(", ")}
						{bare.length > 8 ? ` and ${fmt(bare.length - 8)} more` : ""}. hrms leaves them off the run
						without a word, so they are not paid. Each needs a Salary Structure Assignment on the site.
					</Gap>
				) : null}

				<div className="mt-[.7rem]">
					{noList.length ? (
						<Gap>
							<b>{fmt(noList.length)} of {fmt(run.length)} people in this run have no{" "}
							<code>holiday_list</code></b>. Without one, a week-off and a public holiday are
							working days that nobody worked, and the run takes the pay for them off somebody who
							was never expected in. {fmt(lists)} holiday{lists === 1 ? " list exists" : " lists exist"}{" "}
							on the site; what is missing is the assignment, not the list.
						</Gap>
					) : null}
				</div>

			</div>
		</>
	);
}
