	/* Read once, on arrival. Every other screen pays nothing for it. */
	useEffect(() => { void spProbe(); }, []);

	/* Both resolved at render rather than seeded in the store: this is the one
	   screen where the month decides what everybody is paid, and a default fixed
	   at module load is a default that is wrong for anybody who left the tab open
	   over a month end. */
	const year = f.year || fyOf(todayIso());
	const months = fyMonths(year);
	const now = todayIso().slice(0, 7);
	/* Their capture had the last month of the chosen year selected while the
	   clock was well past it, which is what a year you are no longer in looks
	   like. Same rule here: this month if it is in this year, otherwise the last
	   one that is. */
	const month = f.month && months.some(([ym]) => ym === f.month)
		? f.month
		: (months.some(([ym]) => ym === now) ? now : months[months.length - 1][0]);

	const per = periodOf(month);
	const [start, end] = per.iso;
	const label = (MON[Number(month.slice(5, 7)) - 1] + " " + month.slice(0, 4)).toUpperCase();

	const run = runFor(s, per.iso);
	const joined = run.filter((e) => e.date_of_joining >= start && e.date_of_joining <= end);
	const leftIn = s.spLeft
		? run.filter((e) => {
			const rel = s.spLeft[e.name];
			return rel && rel >= start && rel <= end;
		})
		: null;

	/* The two things that decide payment days, and both are the blocker rather
	   than a detail of it: without a holiday list a week-off is a working day
	   that nobody worked, and without Attendance there is nothing to divide the
	   month by at all. */
