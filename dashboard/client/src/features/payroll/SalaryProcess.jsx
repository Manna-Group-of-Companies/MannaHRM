/* Factor HR's SALARY PROCESS, photographed 29 August 2026 on MAR 2026, drawn
   control for control: three lists, the strip of twelve month chips with a "+"
   on the end, the summary line, the six tiles, Generated By / On with Payslip
   Remarks, and then Start Salary Process, Finalize Process and the gear.

   The screen splits cleanly in two, and the split is the honest part of it:

   **Above the summary line it is date arithmetic**, and all of it is live here.
   Which payroll year, which month, what the payroll period is and how many
   calendar days it holds are answerable without reading a single payroll row —
   they are the same twelve months the Payslip screen already walks, off the
   same fyMonths().

   **Below it, it is payroll state**, and none of that is readable: no payroll
   doctype is on the proxy's allowlist and no Payroll Entry has ever run. So the
   tiles are filled from `Employee` where `Employee` can honestly answer, and
   left as a dash where nothing on this side means what the tile means. Two of
   the six are the second kind, and that is a finding rather than a shortfall —
   see SP_TILES.

   The three buttons all write, so all three open on the site. The gear is worth
   more than it looks: it goes to Payroll Settings, where **Consider Unmarked
   Attendance As** decides whether a day the shift job has not processed yet is
   a day's pay gone. CLAUDE.md §5 arriving from the payroll side. */

/** Their date format on the summary line — "01 Mar - 31 Mar 2026". Not `dmy`,
    which writes 01-Mar-2026: this is one line of their screen and it is written
    the way that line writes it, so the two can be read side by side. */
const spanSaid = (a, b) =>
	`${a.getDate().toString().padStart(2, "0")} ${MON[a.getMonth()]} - `
	+ `${b.getDate().toString().padStart(2, "0")} ${MON[b.getMonth()]} ${b.getFullYear()}`;

/** First day, last day and the calendar-day count of a `YYYY-MM`. */
function periodOf(ym) {
	const [y, m] = String(ym).split("-").map(Number);
	const from = new Date(y, m - 1, 1);
	const till = new Date(y, m, 0);
	return { from, till, days: till.getDate(), iso: [ym + "-01", ym + "-" + till.getDate()] };
}

/* One extra read, made the first time somebody opens this screen — not part of
   the load every page pays for.

   `relieving_date` is asked for on its own because their −13 tile is precisely
   the question of whether this site carries it, and a field the site does not
   have would fail the read that draws the whole dashboard if it were added to
   EMP_FIELDS. A refusal is an answer, and it is a different answer from nobody
   having left in the month: the page says which it got. */
async function spProbe() {
	if (getState().spLeftState) return;
	set({ spLeftState: "loading" });

	const rows = await listAll("Employee", ["name", "relieving_date"]).catch(() => null);

	set(rows
		? { spLeft: Object.fromEntries(rows.map((r) => [r.name, r.relieving_date || ""])), spLeftState: "ok" }
		: { spLeft: null, spLeftState: "absent" });
}

/** Who the run would produce a slip for, in the chosen month.

    Employment overlapping the month, not "Active today" — somebody who left on
    the 14th is still owed fourteen days, which is what their tile's "incl. left"
    is about. When `relieving_date` could not be read the rule falls back to
    status and the page says so rather than quietly counting a different
    population: refusing somebody who did work is the expensive mistake, so the
    fallback keeps everybody Active and loses only the part-month leavers. */
function runFor(s, iso) {
	const [start, end] = iso;
	const left = s.spLeft;

	return scoped(s).filter((e) => {
		if (e.date_of_joining && e.date_of_joining > end) return false;
		if (left) {
			const rel = left[e.name];
			return rel ? rel >= start : e.status !== "Left";
		}
		return e.status === "Active";
	});
}

/** One tile. `n` is the figure, `s` the small print under the label, and a null
    `n` is drawn as a dash with the reason on it — the two tiles nothing here
    can mean are the point of the strip, not a gap in it. */
function SpTile({ label, sub, n, why, warn }) {
	return (
		<div className={"sptile" + (n == null ? " dead" : "") + (warn ? " warn" : "")} title={why}>
			<span className="k">
				{label}
				{sub ? <small> {sub}</small> : null}
			</span>
			<b className="n">{n == null ? "—" : n}</b>
		</div>
	);
}

/** What this screen can honestly put in a file: who the chosen month's run
    would cover, and whether each of them has the two things that decide their
    payment days. Not a payroll file — there is no amount on this side to put
    in one, and the heading row says so. */
function spCsv(rows, ym, s) {
	const cols = ["Employee code", "Name", "Company", "Status", "Joined", "Relieved",
		"Holiday list", "Month"];
	download(
		"salary-process-" + ym + ".csv",
		toCsv(cols, rows.map((e) => [
			e.employee_number || e.name,
			e.employee_name || "",
			e.company || "",
			e.status || "",
			e.date_of_joining || "",
			(s.spLeft && s.spLeft[e.name]) || "",
			e.holiday_list || "",
			ym,
		])),
	);
}

